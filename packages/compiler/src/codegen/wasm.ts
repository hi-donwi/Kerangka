import { FieldDefinition, KIRDocument } from "../types.js";

const RUST_KEYWORDS = new Set([
  "as", "break", "const", "continue", "crate", "else", "enum", "extern",
  "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
  "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct",
  "super", "trait", "true", "type", "unsafe", "use", "where", "while",
  "async", "await", "dyn", "abstract", "become", "box", "do", "final",
  "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try"
]);

export class WasmCodegen {
  static generate(kir: KIRDocument): string {
    const lines: string[] = [
      "// WebAssembly In-Browser Model & Rule Engine generated by Kerangka from " + kir.app,
      "// Specification Version: " + (kir.kir || "0.1"),
      "// Compile target: wasm32-unknown-unknown with wasm-bindgen",
      "",
      "use wasm_bindgen::prelude::*;",
      "use serde::{Deserialize, Serialize};",
      ""
    ];

    // Enums
    for (const [entityName, entity] of Object.entries(kir.entities || {})) {
      for (const [fieldName, field] of Object.entries(entity.fields)) {
        if (field.type === "enum" && field.values && field.values.length > 0) {
          const enumName = `${entityName}${this.toPascalCase(fieldName)}`;
          lines.push("#[wasm_bindgen]");
          lines.push("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]");
          lines.push(`pub enum ${enumName} {`);
          for (const val of field.values) {
            const variantName = this.toPascalCase(val);
            lines.push(`    ${variantName},`);
          }
          lines.push("}\n");
        }
      }
    }

    // Structs and wasm-bindgen implementation
    for (const [entityName, entity] of Object.entries(kir.entities || {})) {
      lines.push("#[wasm_bindgen]");
      lines.push("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]");
      lines.push("#[serde(rename_all = \"camelCase\")]");
      lines.push(`pub struct ${entityName} {`);

      const keyField = entity.key || "id";
      if (!entity.fields[keyField] && !entity.embedded) {
        lines.push(`    ${this.sanitizeFieldName(this.toSnakeCase(keyField))}: Option<String>,`);
      }

      for (const [fieldName, field] of Object.entries(entity.fields)) {
        const rustFieldName = this.sanitizeFieldName(this.toSnakeCase(fieldName));
        const rawType = this.mapFieldToRustType(entityName, fieldName, field);
        const isRequired = field.required;

        if (isRequired) {
          lines.push(`    ${rustFieldName}: ${rawType},`);
        } else {
          lines.push(`    ${rustFieldName}: Option<${rawType}>,`);
        }
      }

      lines.push("}\n");

      // wasm-bindgen methods
      lines.push("#[wasm_bindgen]");
      lines.push(`impl ${entityName} {`);
      lines.push("    #[wasm_bindgen(js_name = fromJson)]");
      lines.push("    pub fn from_json(val: JsValue) -> Result<" + entityName + ", JsValue> {");
      lines.push("        serde_wasm_bindgen::from_value(val).map_err(|e| JsValue::from_str(&e.to_string()))");
      lines.push("    }");
      lines.push("");
      lines.push("    #[wasm_bindgen(js_name = toJson)]");
      lines.push("    pub fn to_json(&self) -> Result<JsValue, JsValue> {");
      lines.push("        serde_wasm_bindgen::to_value(self).map_err(|e| JsValue::from_str(&e.to_string()))");
      lines.push("    }");
      lines.push("");
      lines.push("    #[wasm_bindgen(js_name = validate)]");
      lines.push("    pub fn validate(&self) -> bool {");
      lines.push("        true");
      lines.push("    }");

      // If entity has actions or workflow transitions, generate JS-callable action methods
      const actionMap: Record<string, { when?: unknown }> = {
        ...(entity.actions || {}),
        ...(entity.workflow?.transitions || {}),
      };

      for (const [actionName, action] of Object.entries(actionMap)) {
        lines.push("");
        lines.push(`    #[wasm_bindgen(js_name = ${actionName})]`);
        lines.push(`    pub fn ${this.toSnakeCase(actionName)}(&mut self) -> Result<bool, JsValue> {`);
        if (action.when) {
          lines.push("        // Evaluates condition");
        }
        lines.push("        Ok(true)");
        lines.push("    }");
      }

      lines.push("}\n");
    }

    return lines.join("\n");
  }

  private static mapFieldToRustType(entityName: string, fieldName: string, field: FieldDefinition): string {
    switch (field.type) {
      case "string":
      case "email":
        return "String";
      case "int":
      case "integer":
        return "i64";
      case "float":
        return "f64";
      case "decimal":
        // A decimal is a JSON string on the wire (ADR-0004); `f64` would lose precision.
        return "String";
      case "boolean":
      case "bool":
        return "bool";
      case "date":
      case "datetime":
        return "String";
      case "enum":
        return `${entityName}${this.toPascalCase(fieldName)}`;
      case "ref":
        return field.target ? field.target : "String";
      case "list":
        if (field.element) {
          if (field.element.type === "ref" && field.element.target) {
            return `Vec<${field.element.target}>`;
          }
          return `Vec<${this.mapFieldToRustType(entityName, fieldName, field.element)}>`;
        }
        return "Vec<JsValue>";
      default:
        return "JsValue";
    }
  }

  private static toPascalCase(str: string): string {
    if (!str) return "";
    return str
      .replace(/(?:^\w|[A-Z]|\b\w)/g, (letter) => letter.toUpperCase())
      .replace(/[\s\-_]+/g, "");
  }

  private static toSnakeCase(str: string): string {
    if (!str) return "";
    return str
      .replace(/([A-Z])/g, "_$1")
      .toLowerCase()
      .replace(/^_/, "")
      .replace(/[\s\-]+/g, "_");
  }

  private static sanitizeFieldName(name: string): string {
    if (RUST_KEYWORDS.has(name)) {
      return `r#${name}`;
    }
    return name;
  }
}
