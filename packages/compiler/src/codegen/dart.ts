import { FieldDefinition, KIRDocument } from "../types.js";

const DART_KEYWORDS = new Set([
  "abstract", "as", "assert", "async", "await", "break", "case", "catch",
  "class", "const", "continue", "covariant", "default", "deferred", "do",
  "dynamic", "else", "enum", "export", "extends", "extension", "external",
  "factory", "false", "final", "finally", "for", "Function", "get", "hide",
  "if", "implements", "import", "in", "interface", "is", "late", "library",
  "mixin", "new", "null", "on", "operator", "part", "required", "rethrow",
  "return", "set", "show", "static", "super", "switch", "sync", "this",
  "throw", "true", "try", "typedef", "var", "void", "while", "with", "yield"
]);

export class DartCodegen {
  static generate(kir: KIRDocument): string {
    const lines: string[] = [
      "// Dart Model Definitions generated by Kerangka from " + kir.app,
      "// Specification Version: " + (kir.kir || "0.1"),
      "",
    ];

    // Enums
    for (const [entityName, entity] of Object.entries(kir.entities || {})) {
      for (const [fieldName, field] of Object.entries(entity.fields)) {
        if (field.type === "enum" && field.values && field.values.length > 0) {
          const enumName = `${entityName}${this.toPascalCase(fieldName)}`;
          lines.push(`enum ${enumName} {`);
          for (let i = 0; i < field.values.length; i++) {
            const val = field.values[i];
            if (!val) continue;
            const suffix = i === field.values.length - 1 ? ";" : ",";
            lines.push(`  ${this.sanitizeName(this.toCamelCase(val))}${suffix}`);
          }
          lines.push("");
          lines.push("  String toJson() => name;");
          lines.push(`  static ${enumName} fromJson(String value) {`);
          lines.push(`    return ${enumName}.values.firstWhere(`);
          lines.push(`      (e) => e.name == value,`);
          lines.push(`      orElse: () => ${enumName}.values.first,`);
          lines.push("    );");
          lines.push("  }");
          lines.push("}\n");
        }
      }
    }

    // Classes
    for (const [entityName, entity] of Object.entries(kir.entities || {})) {
      lines.push(`class ${entityName} {`);

      const keyField = entity.key || "id";
      const hasKeyField = !!entity.fields[keyField] || entity.embedded;

      // Fields
      if (!hasKeyField) {
        lines.push(`  final String? ${this.sanitizeName(this.toCamelCase(keyField))};`);
      }

      for (const [fieldName, field] of Object.entries(entity.fields)) {
        const dartFieldName = this.sanitizeName(this.toCamelCase(fieldName));
        const dartType = this.mapFieldToDartType(entityName, fieldName, field);
        const nullable = field.required ? "" : "?";
        lines.push(`  final ${dartType}${nullable} ${dartFieldName};`);
      }

      lines.push("");

      // Constructor
      lines.push(`  const ${entityName}({`);
      if (!hasKeyField) {
        lines.push(`    this.${this.sanitizeName(this.toCamelCase(keyField))},`);
      }
      for (const [fieldName, field] of Object.entries(entity.fields)) {
        const dartFieldName = this.sanitizeName(this.toCamelCase(fieldName));
        const reqPrefix = field.required ? "required " : "";
        lines.push(`    ${reqPrefix}this.${dartFieldName},`);
      }
      lines.push("  });\n");

      // fromJson
      lines.push(`  factory ${entityName}.fromJson(Map<String, dynamic> json) {`);
      lines.push(`    return ${entityName}(`);
      if (!hasKeyField) {
        const prop = this.sanitizeName(this.toCamelCase(keyField));
        lines.push(`      ${prop}: json['${keyField}'] as String?,`);
      }
      for (const [fieldName, field] of Object.entries(entity.fields)) {
        const dartProp = this.sanitizeName(this.toCamelCase(fieldName));
        const parseExpr = this.renderFromJsonExpr(entityName, fieldName, field, `json['${fieldName}']`);
        lines.push(`      ${dartProp}: ${parseExpr},`);
      }
      lines.push("    );");
      lines.push("  }\n");

      // toJson
      lines.push("  Map<String, dynamic> toJson() {");
      lines.push("    final data = <String, dynamic>{};");
      if (!hasKeyField) {
        const prop = this.sanitizeName(this.toCamelCase(keyField));
        lines.push(`    if (${prop} != null) data['${keyField}'] = ${prop};`);
      }
      for (const [fieldName, field] of Object.entries(entity.fields)) {
        const dartProp = this.sanitizeName(this.toCamelCase(fieldName));
        const serializeExpr = this.renderToJsonExpr(entityName, fieldName, field, dartProp);
        if (field.required) {
          lines.push(`    data['${fieldName}'] = ${serializeExpr};`);
        } else {
          lines.push(`    if (${dartProp} != null) data['${fieldName}'] = ${serializeExpr};`);
        }
      }
      lines.push("    return data;");
      lines.push("  }");

      lines.push("}\n");
    }

    return lines.join("\n");
  }

  private static mapFieldToDartType(entityName: string, fieldName: string, field: FieldDefinition): string {
    switch (field.type) {
      case "string":
      case "email":
        return "String";
      case "int":
      case "integer":
        return "int";
      case "float":
        return "double";
      case "decimal":
        // A decimal is a JSON string on the wire (ADR-0004); `double` would lose precision.
        return "String";
      case "boolean":
      case "bool":
        return "bool";
      case "date":
      case "datetime":
        return "DateTime";
      case "enum":
        return `${entityName}${this.toPascalCase(fieldName)}`;
      case "ref":
        return field.target ? field.target : "String";
      case "list":
        if (field.element) {
          if (field.element.type === "ref" && field.element.target) {
            return `List<${field.element.target}>`;
          }
          return `List<${this.mapFieldToDartType(entityName, fieldName, field.element)}>`;
        }
        return "List<dynamic>";
      default:
        return "dynamic";
    }
  }

  private static renderFromJsonExpr(
    entityName: string,
    fieldName: string,
    field: FieldDefinition,
    accessor: string
  ): string {
    switch (field.type) {
      case "string":
      case "email":
      case "ref":
        return `${accessor} as String?`;
      case "int":
      case "integer":
        return `${accessor} as int?`;
      case "float":
        return `(${accessor} as num?)?.toDouble()`;
      case "decimal":
        return `${accessor} as String?`;
      case "boolean":
      case "bool":
        return `${accessor} as bool?`;
      case "date":
      case "datetime":
        return `${accessor} != null ? DateTime.parse(${accessor} as String) : null`;
      case "enum": {
        const enumType = `${entityName}${this.toPascalCase(fieldName)}`;
        return `${accessor} != null ? ${enumType}.fromJson(${accessor} as String) : null`;
      }
      case "list":
        return `(${accessor} as List<dynamic>?)?.cast()`;
      default:
        return accessor;
    }
  }

  private static renderToJsonExpr(
    entityName: string,
    fieldName: string,
    field: FieldDefinition,
    prop: string
  ): string {
    switch (field.type) {
      case "enum":
        return `${prop}?.toJson()`;
      case "date":
      case "datetime":
        return `${prop}?.toIso8601String()`;
      default:
        return prop;
    }
  }

  private static toPascalCase(str: string): string {
    if (!str) return "";
    return str
      .replace(/(?:^\w|[A-Z]|\b\w)/g, (letter) => letter.toUpperCase())
      .replace(/[\s\-_]+/g, "");
  }

  private static toCamelCase(str: string): string {
    if (!str) return "";
    const pascal = this.toPascalCase(str);
    return pascal.charAt(0).toLowerCase() + pascal.slice(1);
  }

  private static sanitizeName(name: string): string {
    if (DART_KEYWORDS.has(name)) {
      return `${name}_`;
    }
    return name;
  }
}
